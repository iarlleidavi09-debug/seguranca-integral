import { render, screen, waitFor, fireEvent } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { beforeEach, describe, expect, it, vi } from 'vitest';
import { questionarioV3 as q } from '../test/questionarioV3';
import Pedido from './Pedido';
import { girarImagem } from './girarImagem';
import { salvarRascunhoV3, vazioV3 } from './rascunhoV3';
vi.mock('./girarImagem', () => ({ girarImagem: vi.fn() }));
const relato = 'Preciso conversar com a equipe sobre o que aconteceu.';
const envios = () => vi.mocked(fetch).mock.calls.filter(([url]) => url === '/api/v4/denuncias');
const form = (i = 0) => envios()[i][1]!.body as FormData;
function preencherTurma() {
  fireEvent.change(screen.getByLabelText('Seu ano'), { target: { value: '8º ano' } });
  fireEvent.change(screen.getByLabelText('Sua sala'), { target: { value: 'B' } });
}
async function revisar(user: ReturnType<typeof userEvent.setup>) {
  await user.click(await screen.findByRole('button', { name: 'Continuar só com o relato' }));
  await user.type(screen.getByLabelText('O que aconteceu?'), relato);
  preencherTurma();
  await user.click(screen.getByRole('button', { name: 'Continuar' }));
}
describe('Pedido v3', () => {
  it('mantém recibo após falha ambígua mesmo quando o relato é editado', async () => {
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />); await revisar(user);
    vi.mocked(fetch).mockRejectedValueOnce(new Error('confirmacao perdida'));
    await user.click(screen.getByRole('button', { name: 'Enviar pedido de ajuda' }));
    await screen.findByRole('alert');
    const recibo = form().get('envio_id');
    await user.click(screen.getByRole('button', { name: 'Editar relato' }));
    fireEvent.change(screen.getByLabelText('O que aconteceu?'), { target: { value: relato + ' Mais um detalhe.' } });
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    vi.mocked(fetch).mockResolvedValueOnce(new Response('{"erro":"envio_id ja utilizado com outro conteudo"}', { status: 409 }));
    await user.click(screen.getByRole('button', { name: 'Enviar pedido de ajuda' }));
    await screen.findByRole('alert');
    expect(form(1).get('envio_id')).toBe(recibo);
    expect(form(1).get('relato')).toBe(relato + ' Mais um detalhe.');
    expect(screen.queryByRole('button', { name: 'Confirmar envio sem respostas' })).not.toBeInTheDocument();
  });
  it('guarda respostas comuns mesmo sem seleção de situações ou relato', async () => {
    const user = userEvent.setup(); const primeira = render(<Pedido onEnviado={() => {}} />);
    await screen.findByText(q.grupos[0].nome, { exact: false });
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    await user.click(screen.getByRole('radio', { name: 'Sim' }));
    const salvo = JSON.parse(localStorage.getItem('si-aluno-pedido-v3')!);
    expect(salvo.respostas).toEqual({ 'q-seguranca': ['q-seguranca.sim'] });
    expect(salvo.marcadas).toEqual([]);
    primeira.unmount(); render(<Pedido onEnviado={() => {}} />);
    await screen.findByText(q.grupos[0].nome, { exact: false });
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    expect(screen.getByRole('radio', { name: 'Sim' })).toBeChecked();
  });
  it('trocar dinheiro por intimidade elimina a perda e mostra somente o novo ramo', async () => {
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />);
    await user.click(await screen.findByText(q.grupos[1].nome, { exact: false }));
    await user.click(screen.getByRole('checkbox', { name: 'Pressão ou chantagem para fazer algo' }));
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    const exigencia = q.perguntas.find(p => p.id === 'q-exigencia')!;
    while (!screen.queryByText(exigencia.texto)) await user.click(screen.getByRole('button', { name: 'Continuar' }));
    await user.click(screen.getByRole('radio', { name: 'Dinheiro ou pertences' }));
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    await user.click(screen.getByRole('radio', { name: 'Dinheiro' }));
    await user.click(screen.getByRole('button', { name: 'Voltar' }));
    await user.click(screen.getByRole('radio', { name: 'Fotos ou algo íntimo' }));
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    expect(screen.getByText(q.perguntas.find(p => p.id === 'q-contato-atual')!.texto)).toHaveFocus();
    await user.click(screen.getByRole('radio', { name: 'Sim' }));
    await user.click(screen.getByRole('button', { name: 'Ir para o relato' }));
    fireEvent.change(screen.getByLabelText('O que aconteceu?'), { target: { value: relato } });
    preencherTurma();
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    await user.click(screen.getByRole('button', { name: 'Enviar pedido de ajuda' }));
    await waitFor(() => expect(envios()).toHaveLength(1));
    const respostas = JSON.parse(form().get('respostas') as string).respostas;
    expect(respostas).toEqual({ 'q-exigencia': ['q-exigencia.intimidade'], 'q-contato-atual': ['q-contato-atual.sim'] });
  });
  it('restaura sem renovar prazo e avisa quando o storage bloqueia novas edições', async () => {
    salvarRascunhoV3({ ...vazioV3, relato, marcadas: ['chantagem', 'nao-existe'], respostas: { 'q-adulto': ['q-adulto.sim'] } }, Date.now() - 1000);
    const antes = localStorage.getItem('si-aluno-pedido-v3');
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />);
    await screen.findByText(q.grupos[1].nome, { exact: false });
    expect(localStorage.getItem('si-aluno-pedido-v3')).toBe(antes);
    await user.click(screen.getByRole('button', { name: 'Continuar só com o relato' }));
    expect(screen.getByLabelText('O que aconteceu?')).toHaveValue(relato);
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('bloqueado'); });
    await user.type(screen.getByLabelText('O que aconteceu?'), ' Mais detalhes.');
    expect(screen.getByRole('status')).toHaveTextContent('Este navegador não permite salvar o rascunho.');
  });
  it('mantém relato longo editável e impede revisão até reduzir ao limite', async () => {
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />);
    await user.click(await screen.findByRole('button', { name: 'Continuar só com o relato' }));
    fireEvent.change(screen.getByLabelText('O que aconteceu?'), { target: { value: 'a'.repeat(5001) } });
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    expect(screen.getByRole('alert')).toHaveTextContent('1 caracteres a mais');
    expect(envios()).toHaveLength(0);
    expect(screen.getByLabelText('O que aconteceu?')).toHaveValue('a'.repeat(5001));
  });
  beforeEach(() => vi.mocked(fetch).mockImplementation(async url => new Response(JSON.stringify(url === '/api/v3/questionario' ? q : { codigo: 'ABCD-1234' }), { status: url === '/api/v3/questionario' ? 200 : 201 })));
  it('mostra oito grupos, preserva seleção entre categorias e apresenta revisão editável', async () => {
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />);
    await screen.findByText(q.grupos[0].nome, { exact: false });
    expect(document.querySelectorAll('details')).toHaveLength(8);
    await user.click(screen.getByText(q.grupos[0].nome, { exact: false }));
    await user.click(screen.getByRole('checkbox', { name: q.grupos[0].opcoes[0].texto }));
    await user.click(screen.getByText(q.grupos[1].nome, { exact: false }));
    await user.click(screen.getByRole('checkbox', { name: q.grupos[1].opcoes[0].texto }));
    expect(screen.getByText('2 situações selecionadas')).toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    expect(screen.getByText(q.perguntas.find(p => p.id === q.comuns[0])!.texto)).toHaveFocus();
    await user.click(screen.getByRole('button', { name: 'Ir para o relato' }));
    await user.type(screen.getByLabelText('O que aconteceu?'), relato);
    preencherTurma();
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    expect(screen.getByRole('heading', { name: 'Revise seu pedido' })).toHaveFocus();
    expect(screen.getByText(relato)).toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'Editar situações' }));
    expect(screen.getByRole('checkbox', { name: q.grupos[0].opcoes[0].texto })).toBeChecked();
  });
  it('falha de definição permite relato livre sem respostas', async () => {
    vi.mocked(fetch).mockRejectedValueOnce(new Error('offline'));
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />);
    await revisar(user);
    await user.click(screen.getByRole('button', { name: 'Enviar pedido de ajuda' }));
    await waitFor(() => expect(envios()).toHaveLength(1));
    expect(form().has('respostas')).toBe(false);
    expect(form().get('relato')).toBe(relato);
    expect(form().get('envio_id')).toMatch(/^[a-f0-9]{32}$/);
  });
  it('recupera recibo em retry de rede, bloqueia controles e pede confirmação explícita para descartar respostas', async () => {
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />);
    await screen.findByText(q.grupos[1].nome, { exact: false });
    await user.click(screen.getByText(q.grupos[1].nome, { exact: false }));
    await user.click(screen.getByRole('checkbox', { name: q.grupos[1].opcoes[0].texto }));
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    await user.click(screen.getByRole('button', { name: 'Ir para o relato' }));
    await user.type(screen.getByLabelText('O que aconteceu?'), relato);
    preencherTurma();
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    vi.mocked(fetch).mockRejectedValueOnce(new Error('rede'));
    await user.click(screen.getByRole('button', { name: 'Enviar pedido de ajuda' }));
    expect(await screen.findByRole('alert')).toHaveTextContent('Seu relato continua nesta tela');
    vi.mocked(fetch).mockResolvedValueOnce(new Response('{"erro":"respostas invalidas"}', { status: 400 }));
    await user.click(screen.getByRole('button', { name: 'Enviar pedido de ajuda' }));
    await screen.findByRole('button', { name: 'Confirmar envio sem respostas' });
    expect(envios()).toHaveLength(2);
    expect(form(1).get('envio_id')).toBe(form(0).get('envio_id'));
    expect(form(1).get('respostas')).toBe(form(0).get('respostas'));
    vi.mocked(fetch).mockRejectedValueOnce(new Error('confirmacao perdida'));
    await user.click(screen.getByRole('button', { name: 'Confirmar envio sem respostas' }));
    await waitFor(() => expect(envios()).toHaveLength(3));
    expect(form(2).has('respostas')).toBe(false);
    expect(form(2).get('envio_id')).not.toBe(form(1).get('envio_id'));
    expect(await screen.findByRole('alert')).toHaveTextContent('Seu relato continua nesta tela');
    await user.click(screen.getByRole('button', { name: 'Enviar pedido de ajuda' }));
    await waitFor(() => expect(envios()).toHaveLength(4));
    expect(form(3).has('respostas')).toBe(false);
    expect(form(3).get('envio_id')).toBe(form(2).get('envio_id'));
  });
  it('bloqueia envio durante giro e preserva anexos ao editar revisão', async () => {
    const user = userEvent.setup(); render(<Pedido onEnviado={() => {}} />); await revisar(user);
    const arquivo = new File(['imagem'], 'prova.png', { type: 'image/png' });
    await user.upload(screen.getByLabelText('Adicionar imagens'), arquivo);
    let finalizar!: (file: File) => void;
    vi.mocked(girarImagem).mockImplementationOnce(() => new Promise(resolve => { finalizar = resolve; }));
    await user.click(screen.getByRole('button', { name: 'Girar prova.png' }));
    expect(screen.getByRole('button', { name: 'Enviar pedido de ajuda' })).toBeDisabled();
    await user.click(screen.getByRole('button', { name: 'Editar relato' }));
    await user.click(screen.getByRole('button', { name: 'Continuar' }));
    expect(screen.getByAltText('Prévia de prova.png')).toBeInTheDocument();
    finalizar(arquivo);
    await waitFor(() => expect(screen.getByRole('button', { name: 'Enviar pedido de ajuda' })).toBeEnabled());
  });
});
