import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const aluno = process.env.ALUNO_URL || 'http://127.0.0.1:53100';
const coord = process.env.COORD_URL || 'http://127.0.0.1:53101';
const saida = path.resolve('../.superpowers/sdd/2026-10-17-mapa-escolar/navegador');
await mkdir(saida, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
const pagina = await context.newPage();
const erros = [];
context.on('page', p => p.on('pageerror', e => erros.push(e.message)));
pagina.on('pageerror', e => erros.push(e.message));
const resultados = [];
const registrar = texto => { resultados.push(texto); console.log(texto); };
const respostaOk = async r => { expect(r.ok(), await r.text()).toBeTruthy(); return r.json(); };
try {
  const setup = await respostaOk(await context.request.get(`${coord}/api/setup`));
  if (setup.pendente) await respostaOk(await context.request.post(`${coord}/api/setup`, { data: { nome: 'teste-mapa', senha: 'SomenteTesteMapa-2026!' } }));
  await respostaOk(await context.request.post(`${coord}/api/login`, { data: { nome: 'teste-mapa', senha: 'SomenteTesteMapa-2026!' } }));
  await pagina.goto(`${coord}/#mapa`);
  await expect(pagina.getByRole('heading', { name: 'Mapa da escola' })).toBeVisible();
  const estadoInicial = await respostaOk(await context.request.get(`${coord}/api/mapa`));
  expect(estadoInicial.ambientes).toHaveLength(0);
  await pagina.getByRole('button', { name: 'Editar planta', exact: true }).click();
  await pagina.getByRole('combobox', { name: /Formato do novo ambiente/ }).selectOption('l');
  await pagina.getByRole('combobox', { name: /Rotação do novo ambiente/ }).selectOption('90');
  await pagina.getByLabel('Espessura dos novos braços (%)', { exact: true }).fill('40');
  await pagina.getByRole('button', { name: 'Desenhar em L', exact: true }).click();
  const planta = pagina.getByRole('group', { name: 'Planta esquemática do nível atual' });
  await planta.scrollIntoViewIfNeeded();
  const caixa = await planta.boundingBox();
  await pagina.mouse.move(caixa.x + caixa.width * .08, caixa.y + caixa.height * .08);
  await pagina.mouse.down();
  await pagina.mouse.move(caixa.x + caixa.width * .55, caixa.y + caixa.height * .45, { steps: 12 });
  await pagina.mouse.up();
  await pagina.getByLabel('Nome do ambiente', { exact: true }).fill('Ala A');
  await pagina.getByRole('button', { name: 'Aplicar alterações', exact: true }).click();
  await expect(pagina.locator('.mapa-planta polygon')).toHaveCount(1);
  await pagina.getByRole('navigation', { name: 'Principal' }).getByRole('button', { name: 'Casos', exact: true }).click();
  await pagina.getByRole('navigation', { name: 'Principal' }).getByRole('button', { name: 'Mapa da escola', exact: true }).click();
  await expect(pagina.getByLabel('Nome do ambiente', { exact: true })).toHaveValue('Ala A');
  await pagina.getByRole('button', { name: 'Abrir este nível', exact: true }).click();
  await pagina.getByRole('combobox', { name: /Formato do novo ambiente/ }).selectOption('retangulo');
  await pagina.getByLabel('Nome do novo ambiente', { exact: true }).fill('2º andar');
  await pagina.getByRole('combobox', { name: /Tipo do novo ambiente/ }).selectOption('andar');
  await pagina.getByRole('button', { name: 'Adicionar ambiente', exact: true }).click();
  await pagina.getByRole('button', { name: 'Abrir este nível', exact: true }).click();
  await pagina.getByLabel('Nome do novo ambiente', { exact: true }).fill('Sala 201');
  await pagina.getByRole('combobox', { name: /Tipo do novo ambiente/ }).selectOption('sala');
  await pagina.getByRole('button', { name: 'Adicionar ambiente', exact: true }).click();
  await pagina.getByRole('button', { name: 'Salvar planta', exact: true }).click();
  await expect(pagina.getByText('Planta salva.', { exact: true })).toBeVisible();
  await pagina.reload();
  await pagina.getByLabel('Buscar ambiente', { exact: true }).fill('201');
  await pagina.getByRole('button', { name: 'Ala A / 2º andar / Sala 201', exact: true }).click();
  await expect(pagina.getByRole('heading', { name: 'Sala 201', exact: true })).toBeVisible();
  const estado = await respostaOk(await context.request.get(`${coord}/api/mapa`));
  const sala = estado.ambientes.find(a => a.nome === 'Sala 201');
  expect(estado.ambientes).toHaveLength(3);
  expect(estado.ambientes.find(a => a.nome === 'Ala A')).toMatchObject({ formato: 'l', rotacao: 90, espessura: .4 });
  registrar('Planta vazia: ala em L com rotação/espessura, nome, rascunho entre telas, hierarquia, salvar, recarregar e busca.');

  const estudante = await context.newPage();
  await estudante.goto(aluno);
  await estudante.getByRole('navigation', { name: 'Principal' }).getByRole('button', { name: 'Pedir ajuda', exact: true }).click();
  await estudante.getByRole('button', { name: 'Continuar só com o relato', exact: true }).click();
  await estudante.getByLabel('O que aconteceu?', { exact: true }).fill('Relato fictício para verificar a integração do mapa escolar.');
  await estudante.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(estudante.getByRole('alert')).toContainText('Informe seu ano');
  await estudante.getByLabel('Seu ano', { exact: true }).fill('8º ano');
  await estudante.getByLabel('Sua sala', { exact: true }).fill('B');
  await estudante.getByLabel('Local no mapa da escola', { exact: true }).selectOption(sala.id);
  await estudante.getByRole('button', { name: 'Continuar', exact: true }).click();
  await expect(estudante.getByText('Ala A / 2º andar / Sala 201', { exact: true })).toBeVisible();
  const envio = estudante.waitForResponse(r => r.url() === `${aluno}/api/v4/denuncias` && r.request().method() === 'POST');
  await estudante.getByRole('button', { name: 'Enviar pedido de ajuda', exact: true }).click();
  const resposta = await envio;
  expect(resposta.status()).toBe(201);
  const { codigo } = await resposta.json();
  const fila = await respostaOk(await context.request.get(`${coord}/api/casos`));
  const casoId = fila.casos[0].id;
  const detalhe = await respostaOk(await context.request.get(`${coord}/api/casos/${casoId}`));
  expect(detalhe.nome).toBeNull();
  expect(detalhe.ano_relator).toBe('8º ano');
  expect(detalhe.sala_relator).toBe('B');
  registrar('Relato anônimo: ano/sala obrigatórios, seleção hierárquica e persistência no caso.');

  await pagina.goto(`${coord}/#caso-${casoId}`);
  await expect(pagina.getByRole('heading', { name: 'Registrar resolução', exact: true })).toBeVisible();
  await pagina.getByRole('radio', { name: 'Situação solucionada', exact: true }).check();
  await pagina.getByLabel('Providências', { exact: true }).fill('Providência fictícia visível para o aluno.');
  await pagina.getByLabel('Nome do autor 1', { exact: true }).fill('Pessoa fictícia reservada');
  await pagina.getByLabel('Ano do autor 1', { exact: true }).fill('9º ano');
  await pagina.getByLabel('Sala do autor 1', { exact: true }).fill('C');
  const png = Buffer.from(await pagina.evaluate(() => { const c = document.createElement('canvas'); c.width = 12; c.height = 12; c.getContext('2d').fillRect(0, 0, 12, 12); return c.toDataURL('image/png').split(',')[1]; }), 'base64');
  await pagina.getByLabel('Foto do autor 1 (opcional)', { exact: true }).setInputFiles({ name: 'foto-ficticia.png', mimeType: 'image/png', buffer: png });
  const finalizacao = pagina.waitForResponse(r => r.url() === `${coord}/api/v4/casos/${casoId}/resolucao` && r.request().method() === 'POST');
  await pagina.getByRole('button', { name: 'Registrar resolução', exact: true }).click();
  expect((await finalizacao).status()).toBe(201);
  await expect(pagina.getByText('Pessoa fictícia reservada', { exact: true })).toBeVisible();
  const interno = await respostaOk(await context.request.get(`${coord}/api/casos/${casoId}`));
  const autor = interno.resolucoes.at(-1).autores[0];
  expect(autor.tem_foto).toBe(true);
  const fotoUrl = `${coord}/api/casos/${casoId}/autores/${autor.id}/foto`;
  expect((await context.request.get(fotoUrl)).status()).toBe(200);
  const semSessao = await browser.newContext();
  expect((await semSessao.request.get(fotoUrl)).status()).toBe(401);
  await semSessao.close();
  const publico = await respostaOk(await context.request.post(`${aluno}/api/acompanhar`, { data: { codigo } }));
  expect(JSON.stringify(publico)).not.toMatch(/Pessoa fictícia reservada|foto_nome|autores|justificativa_autoria/);
  const agregado = await respostaOk(await context.request.get(`${coord}/api/mapa/resumo?base=autores&periodo=30`));
  expect(agregado.total).toBe(1);
  expect(agregado.ambientes[0].anos).toEqual([{ ano: '9º ano', total: 1 }]);
  registrar('Finalização real: autor/foto internos, imagem autenticada, acompanhamento sem identidade e mapa por turma apurada.');
  await pagina.goto(`${coord}/#mapa`);
  await pagina.getByRole('combobox', { name: /Base das turmas/ }).selectOption('autores');
  await expect(pagina.locator('.mapa-contagens')).toContainText('1');
  await pagina.getByRole('navigation', { name: 'Níveis da planta' }).getByRole('button', { name: 'Escola', exact: true }).click();
  await pagina.locator('.mapa-lista').getByRole('button', { name: 'Ala A', exact: true }).click();
  await expect(pagina.locator('.mapa-planta polygon')).toHaveCount(1);
  await pagina.screenshot({ path: path.join(saida, 'mapa-desktop.png'), fullPage: true });
  await pagina.emulateMedia({ colorScheme: 'dark' });
  await pagina.screenshot({ path: path.join(saida, 'mapa-escuro.png'), fullPage: true });
  await pagina.setViewportSize({ width: 390, height: 844 });
  expect(await pagina.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await pagina.screenshot({ path: path.join(saida, 'mapa-mobile.png'), fullPage: true });
  expect(erros).toEqual([]);
  registrar('Interface desktop, tema escuro e celular sem overflow geral; nenhum erro de JavaScript.');
  await writeFile(path.join(saida, 'resultado.json'), JSON.stringify({ ok: true, resultados }, null, 2));
} catch (erro) {
  await pagina.screenshot({ path: path.join(saida, 'falha.png'), fullPage: true }).catch(() => {});
  throw erro;
} finally { await browser.close(); }
